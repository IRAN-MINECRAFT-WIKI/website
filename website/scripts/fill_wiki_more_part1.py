def is_empty_field(value):
    """Return True if value is None, not a list, or an empty list."""
    if value is None:
        return True
    if isinstance(value, list) and len(value) == 0:
        return True
    return False


def fill_block_file(block_id, content):
    """Fill the block JSON file for block_id with the given content dict.
    Only fills fields that are missing or empty. Returns number of fields written."""
    path = BLOCKS_DIR / f"{block_id}.json"
    if not path.exists():
        print(f"  [MISS] {block_id}: file not found")
        return 0
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"  [ERR ] {block_id}: {e}")
        return 0

    written = 0
    for field in WIKI_FIELDS:
        if is_empty_field(data.get(field)):
            data[field] = list(content.get(field, []))
            written += 1
    if is_empty_field(data.get(HISTORY_FIELD)):
        history = content.get(HISTORY_FIELD, [])
        # Ensure each entry is a dict with version & change
        cleaned = []
        for entry in history:
            if isinstance(entry, dict) and "version" in entry and "change" in entry:
                cleaned.append(entry)
        data[HISTORY_FIELD] = cleaned
        written += 1

    if written > 0:
        # Preserve original key order; new fields appended at end via dict insertion.
        # json.dump preserves insertion order in Python 3.7+.
        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"  [OK ] {block_id}: {written} fields written")
    else:
        print(f"  [SKIP] {block_id}: already has content")
    return written


def main():
    total_written = 0
    total_blocks = 0
    for block_id, content in BLOCK_CONTENT.items():
        total_blocks += 1
        total_written += fill_block_file(block_id, content)
    print(f"\nBlocks processed: {total_blocks}")
    print(f"Total field writes: {total_written}")


if __name__ == "__main__":
    main()
