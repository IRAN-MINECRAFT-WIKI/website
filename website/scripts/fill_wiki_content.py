def field_is_empty(obj, key, is_history=False):
    """Return True if field is missing OR an empty list."""
    v = obj.get(key)
    if not isinstance(v, list):
        return True
    if len(v) == 0:
        return True
    return False


def fill_file(filepath, content):
    """Fill one JSON file with content dict (intro/behavior/trivia/differences/history)."""
    if not filepath.exists():
        return False, "file missing"
    try:
        with open(filepath, encoding="utf-8") as f:
            data = json.load(f)
    except Exception as e:
        return False, f"json error: {e}"

    changed = False
    filled_fields = []

    for field in WIKI_FIELDS:
        if field_is_empty(data, field):
            new_val = content.get(field, [])
            if new_val:
                data[field] = list(new_val)
                changed = True
                filled_fields.append(field)

    # history (list of {version, change})
    if field_is_empty(data, HISTORY_FIELD, is_history=True):
        new_hist = content.get(HISTORY_FIELD, [])
        if new_hist:
            data[HISTORY_FIELD] = [dict(h) for h in new_hist]
            changed = True
            filled_fields.append(HISTORY_FIELD)

    if not changed:
        return False, "already has content"

    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return True, filled_fields


def main():
    report = {"blocks": [], "mobs": []}

    # ----- Blocks -----
    print("=" * 60)
    print("Filling BLOCKS")
    print("=" * 60)
    for bid, content in BLOCK_CONTENT.items():
        fp = BLOCKS_DIR / f"{bid}.json"
        ok, info = fill_file(fp, content)
        if ok:
            report["blocks"].append((bid, info))
            print(f"  [FILLED] {bid:20s} -> {info}")
        else:
            print(f"  [SKIP]   {bid:20s} -> {info}")

    # ----- Mobs -----
    print()
    print("=" * 60)
    print("Filling MOBS")
    print("=" * 60)
    for mid, content in MOB_CONTENT.items():
        fp = MOBS_DIR / f"{mid}.json"
        ok, info = fill_file(fp, content)
        if ok:
            report["mobs"].append((mid, info))
            print(f"  [FILLED] {mid:20s} -> {info}")
        else:
            print(f"  [SKIP]   {mid:20s} -> {info}")

    # ----- Summary -----
    print()
    print("=" * 60)
    print("SUMMARY")
    print("=" * 60)
    print(f"Blocks filled: {len(report['blocks'])}")
    print(f"Mobs filled:   {len(report['mobs'])}")
    return report


